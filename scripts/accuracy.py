"""Accuracy check: the app's headline figures against values read from the filings themselves.

The expected values are in scripts/accuracy_fixtures.json, entered line by line from each filing's
financial statements. Needs the network and SEC_USER_AGENT, so it is run by hand, not by the tests:

    uv run --env-file .env python scripts/accuracy.py
"""

import json
from datetime import date
from pathlib import Path

from finance_analyzer import store
from finance_analyzer.display import label

FIXTURES = Path(__file__).with_name("accuracy_fixtures.json")
REPORT = Path(__file__).parents[1] / "docs" / "ACCURACY.md"


def matches(item: str, app_value: float, filed: float) -> bool:
    """Equal once the app's value is rounded the way the filing prints it (millions; EPS to the cent)."""
    shown = app_value if item == "diluted_eps" else app_value / 1e6
    decimals = 2 if item == "diluted_eps" else len(str(filed).split(".")[1]) if "." in str(filed) else 0
    return abs(shown - filed) <= 0.5 * 10**-decimals + 1e-9


assert matches("revenue", 478_834_000_000, 478834) and not matches("revenue", 478_836_000_000, 478834)
assert matches("revenue", 2_894_307_700_000, 2894307.7) and matches("diluted_eps", 4.904, 4.90)


def check(company: dict) -> list[tuple[str, float | None, float | None, str]]:
    """(item, filing value, app value, result) for each figure, result one of ✓ / ✗ / n/a."""
    ticker, end = company["ticker"], date.fromisoformat(company["fiscal_year_end"])
    store.load_company(ticker)
    rows = {row.item: row for row in store.get_company(ticker) if row.fiscal_year_end == end}
    results = []
    for item, expected in company["figures"].items():
        filed, row = expected["value"], rows.get(item)
        app = None if row is None else row.value if item == "diluted_eps" else row.value / 1e6
        if filed is None:
            results.append((item, None, app, "n/a"))
        else:
            results.append((item, filed, app, "✓" if row and matches(item, row.value, filed) else "✗"))
    return results


def main() -> None:
    fixtures = json.loads(FIXTURES.read_text())
    lines, misses, total, matched = [], [], 0, 0
    for company in fixtures["companies"]:
        results = check(company)
        compared = [r for r in results if r[3] != "n/a"]
        total, matched = total + len(compared), matched + sum(r[3] == "✓" for r in compared)
        cells = " | ".join(r[3] for r in results)
        lines.append(f"| [{company['ticker']}]({company['filing']}) | {company['fiscal_year_end']} | {cells} |")
        for item, filed, app, result in results:
            line = company["figures"][item]["line"]
            if result == "✗":
                shown = "missing" if app is None else f"{app:,.2f}"
                note = company["figures"][item].get("note", "")
                misses.append(f"- **{company['ticker']} {label(item)}:** filing {filed:,} (“{line}”), app {shown}. {note}".rstrip())
            elif result == "n/a":
                app_text = "not shown" if app is None else f"calculates {app:,.0f}"
                misses.append(f"- {company['ticker']} {label(item)}: {line}; the app {app_text} (not counted).")
    items = list(fixtures["companies"][0]["figures"])
    report = [
        "# Accuracy: the app against the filings",
        "",
        f"Generated by `scripts/accuracy.py` on {date.today().isoformat()}. For 10 companies it compares 10 headline",
        "figures from the latest fiscal year the app stores with the same figures printed in that year's annual",
        "report, entered line by line in [`scripts/accuracy_fixtures.json`](../scripts/accuracy_fixtures.json)",
        "with the line label and a link to the filing. A figure matches when the app's value, rounded the way",
        "the filing prints it (millions; EPS to the cent), is the same number.",
        "",
        f"**Match rate: {matched} of {total} ({matched / total:.0%}).**",
        "",
        "> The expected values were read from the filings by Claude (the AI assistant that built most of this",
        "> app) and are marked in the fixtures file as waiting for the owner's check. Until then this is a",
        "> self-check, not an independent audit.",
        "",
        "| Company (filing) | Year end | " + " | ".join(label(item) for item in items) + " |",
        "|---|---|" + "---|" * len(items),
        *lines,
        "",
        "✓ matches · ✗ differs · n/a the filing prints no such line, so there's nothing to compare.",
        "",
        "## Differences and figures not compared",
        "",
        *(misses or ["None."]),
        "",
        "How the app chooses each number is in [METHODOLOGY.md](METHODOLOGY.md).",
    ]
    REPORT.write_text("\n".join(report) + "\n")
    print(f"wrote {REPORT}: {matched} of {total} match")


if __name__ == "__main__":
    main()
